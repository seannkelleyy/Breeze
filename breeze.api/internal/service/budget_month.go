package service

import (
	"context"
	"errors"
	"fmt"
	"time"

	"breeze.api/internal/db/sqlc"
	"github.com/google/uuid"
	"github.com/govalues/decimal"
	"github.com/jackc/pgx/v5/pgxpool"
)

// BudgetMonthInput materializes one user-month: the budget row plus the incomes
// and expense categories generated from the user's recurring templates.
type BudgetMonthInput struct {
	UserID          uuid.UUID
	Date            time.Time
	MonthlyIncome   decimal.Decimal
	MonthlyExpenses decimal.Decimal

	// PayrollIncomes replaces the month's PEOPLEPAYROLL incomes. Nil leaves
	// existing payroll rows untouched; an empty non-nil slice clears them.
	PayrollIncomes []PayrollIncome
}

// PayrollIncome is one person's net pay for a budget month.
type PayrollIncome struct {
	PersonID uuid.UUID
	Name     string
	Amount   decimal.Decimal
	Date     time.Time
}

// BudgetMonthService regenerates a budget month from recurring templates and
// replaces its payroll incomes. The whole workflow runs in one transaction: if
// any step fails the month is left exactly as it was.
type BudgetMonthService struct {
	queries *sqlc.Queries
	pool    *pgxpool.Pool
}

func NewBudgetMonthService(queries *sqlc.Queries, pool *pgxpool.Pool) *BudgetMonthService {
	return &BudgetMonthService{queries: queries, pool: pool}
}

// CreateOrUpdate upserts the budget for input.Date and regenerates the rows
// generated from recurring templates. Generated incomes are replaced on every
// run, which makes the operation idempotent. The budget's monthly totals are
// recalculated from the resulting rows rather than from the input amounts.
func (s *BudgetMonthService) CreateOrUpdate(ctx context.Context, input *BudgetMonthInput) (*Budget, error) {
	var budget *Budget
	err := s.inTx(ctx, func(q *sqlc.Queries) error {
		var err error
		budget, err = materializeBudgetMonth(ctx, budgetMonthDeps{
			budgets:           NewBudgetService(q),
			incomes:           NewIncomeService(q),
			categories:        NewExpenseCategoryService(q),
			recurringIncomes:  NewRecurringIncomeService(q),
			recurringExpenses: NewRecurringExpenseService(q),
			cleanup:           q,
		}, input)
		return err
	})
	if err != nil {
		return nil, err
	}
	return budget, nil
}

func (s *BudgetMonthService) inTx(ctx context.Context, fn func(*sqlc.Queries) error) error {
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return fmt.Errorf("begin budget month transaction: %w", err)
	}
	defer func() {
		_ = tx.Rollback(ctx)
	}()

	if err := fn(s.queries.WithTx(tx)); err != nil {
		return err
	}

	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("commit budget month transaction: %w", err)
	}
	return nil
}

// budgetMonthDeps holds the transaction-scoped collaborators of the workflow.
// Keeping them explicit lets the orchestration be tested with narrow fakes.
type budgetMonthDeps struct {
	budgets           *BudgetService
	incomes           *IncomeService
	categories        *ExpenseCategoryService
	recurringIncomes  *RecurringIncomeService
	recurringExpenses *RecurringExpenseService
	cleanup           budgetMonthCleanup
}

// budgetMonthCleanup is the subset of queries needed to clear rows generated by
// a previous run.
type budgetMonthCleanup interface {
	SoftDeleteGeneratedExpensesByBudget(ctx context.Context, budgetID uuid.UUID) (int64, error)
	SoftDeleteGeneratedCategoriesByBudget(ctx context.Context, budgetID uuid.UUID) (int64, error)
}

func materializeBudgetMonth(ctx context.Context, deps budgetMonthDeps, input *BudgetMonthInput) (*Budget, error) {
	budget, err := upsertBudgetMonth(ctx, deps.budgets, input)
	if err != nil {
		return nil, err
	}

	if err := replaceGeneratedIncomes(ctx, deps, input, budget); err != nil {
		return nil, err
	}
	if input.PayrollIncomes != nil {
		if err := replacePayrollIncomes(ctx, deps.incomes, input, budget); err != nil {
			return nil, err
		}
	}
	if err := replaceGeneratedExpenseCategories(ctx, deps, input, budget); err != nil {
		return nil, err
	}

	return recalculateBudgetTotals(ctx, deps, input.UserID, budget)
}

func upsertBudgetMonth(ctx context.Context, budgets *BudgetService, input *BudgetMonthInput) (*Budget, error) {
	existing, err := budgets.GetByDate(ctx, input.UserID, input.Date)
	switch {
	case err == nil:
		return budgets.Update(ctx, input.UserID, &UpdateBudgetInput{
			ID:              existing.ID,
			MonthlyIncome:   input.MonthlyIncome,
			MonthlyExpenses: input.MonthlyExpenses,
		})
	case errors.Is(err, ErrNotFound):
		return budgets.Create(ctx, &CreateBudgetInput{
			UserID:          input.UserID,
			Date:            input.Date,
			MonthlyIncome:   input.MonthlyIncome,
			MonthlyExpenses: input.MonthlyExpenses,
		})
	default:
		return nil, err
	}
}

func replaceGeneratedIncomes(ctx context.Context, deps budgetMonthDeps, input *BudgetMonthInput, budget *Budget) error {
	if err := deleteIncomesBySource(ctx, deps.incomes, input.UserID, budget.ID, sqlc.IncomeSourceTypeRECURRINGTEMPLATE); err != nil {
		return err
	}

	templates, err := deps.recurringIncomes.ListByUserID(ctx, input.UserID)
	if err != nil {
		return fmt.Errorf("list recurring incomes: %w", err)
	}

	monthStart, monthEnd := budgetMonthBounds(input.Date)
	for i := range templates {
		template := &templates[i]
		if !templateCoversMonth(template.StartDate, template.EndDate, monthStart, monthEnd) {
			continue
		}
		for _, occurrence := range recurringOccurrences(template, monthStart, monthEnd) {
			occ := occurrence
			if _, err := deps.incomes.Create(ctx, &CreateIncomeInput{
				UserID:               input.UserID,
				BudgetID:             budget.ID,
				Name:                 template.Name,
				Amount:               template.Amount,
				Date:                 occ,
				SourceType:           sqlc.IncomeSourceTypeRECURRINGTEMPLATE,
				SourceTemplateID:     &template.ID,
				SourceOccurrenceDate: &occ,
				GenerationMonth:      &monthStart,
			}); err != nil {
				return fmt.Errorf("create recurring income: %w", err)
			}
		}
	}
	return nil
}

func replacePayrollIncomes(ctx context.Context, incomes *IncomeService, input *BudgetMonthInput, budget *Budget) error {
	if err := deleteIncomesBySource(ctx, incomes, input.UserID, budget.ID, sqlc.IncomeSourceTypePEOPLEPAYROLL); err != nil {
		return err
	}

	monthStart, _ := budgetMonthBounds(input.Date)
	for i := range input.PayrollIncomes {
		item := &input.PayrollIncomes[i]
		if _, err := incomes.Create(ctx, &CreateIncomeInput{
			UserID:          input.UserID,
			BudgetID:        budget.ID,
			Name:            item.Name,
			Amount:          item.Amount,
			Date:            item.Date,
			PersonID:        &item.PersonID,
			SourceType:      sqlc.IncomeSourceTypePEOPLEPAYROLL,
			GenerationMonth: &monthStart,
		}); err != nil {
			return fmt.Errorf("create payroll income: %w", err)
		}
	}
	return nil
}

func deleteIncomesBySource(ctx context.Context, incomes *IncomeService, userID, budgetID uuid.UUID, source sqlc.IncomeSourceType) error {
	existing, err := incomes.ListByBudgetID(ctx, budgetID)
	if err != nil {
		return fmt.Errorf("list incomes for budget: %w", err)
	}
	for i := range existing {
		if existing[i].SourceType != source {
			continue
		}
		if err := incomes.Delete(ctx, userID, existing[i].ID); err != nil {
			return fmt.Errorf("delete %s income %s: %w", source, existing[i].ID, err)
		}
	}
	return nil
}

func replaceGeneratedExpenseCategories(ctx context.Context, deps budgetMonthDeps, input *BudgetMonthInput, budget *Budget) error {
	if _, err := deps.cleanup.SoftDeleteGeneratedExpensesByBudget(ctx, budget.ID); err != nil {
		return fmt.Errorf("delete generated expenses: %w", err)
	}
	if _, err := deps.cleanup.SoftDeleteGeneratedCategoriesByBudget(ctx, budget.ID); err != nil {
		return fmt.Errorf("delete generated expense categories: %w", err)
	}

	templates, err := deps.recurringExpenses.ListByUserID(ctx, input.UserID)
	if err != nil {
		return fmt.Errorf("list recurring expenses: %w", err)
	}

	monthStart, monthEnd := budgetMonthBounds(input.Date)
	for i := range templates {
		template := &templates[i]
		if !templateCoversMonth(template.StartDate, template.EndDate, monthStart, monthEnd) {
			continue
		}
		if _, err := deps.categories.Create(ctx, &CreateExpenseCategoryInput{
			UserID:           input.UserID,
			BudgetID:         budget.ID,
			Name:             template.Name,
			Allocation:       template.MonthlyAmount(),
			CurrentSpend:     decimal.MustParse("0"),
			SourceType:       sqlc.ExpenseSourceTypeRECURRINGTEMPLATE,
			SourceTemplateID: &template.ID,
			GenerationMonth:  &monthStart,
		}); err != nil {
			return fmt.Errorf("create recurring expense category: %w", err)
		}
	}
	return nil
}

// recalculateBudgetTotals makes the budget's monthly totals match the rows that
// now exist for it.
func recalculateBudgetTotals(ctx context.Context, deps budgetMonthDeps, userID uuid.UUID, budget *Budget) (*Budget, error) {
	incomes, err := deps.incomes.ListByBudgetID(ctx, budget.ID)
	if err != nil {
		return nil, fmt.Errorf("list incomes for budget: %w", err)
	}
	incomeTotal := decimal.MustParse("0")
	for i := range incomes {
		incomeTotal, err = incomeTotal.Add(incomes[i].Amount)
		if err != nil {
			return nil, fmt.Errorf("sum incomes: %w", err)
		}
	}

	categories, err := deps.categories.ListByBudgetID(ctx, budget.ID)
	if err != nil {
		return nil, fmt.Errorf("list expense categories for budget: %w", err)
	}
	expenseTotal := decimal.MustParse("0")
	for i := range categories {
		expenseTotal, err = expenseTotal.Add(categories[i].Allocation)
		if err != nil {
			return nil, fmt.Errorf("sum expense categories: %w", err)
		}
	}

	return deps.budgets.Update(ctx, userID, &UpdateBudgetInput{
		ID:              budget.ID,
		MonthlyIncome:   incomeTotal,
		MonthlyExpenses: expenseTotal,
	})
}
